    // within 3 of the reference in every channel, and within 1 in all but a few: the inverse DCTs round apart at times, and the upsampling and the color
    // conversion are the same.
    [TestMethod]
    public void AJpegOfAnotherEncoder_IsDecodedAsTheIjgDecoderDecodesIt()
    {
        Assert.AreEqual(PictureDecodeFailure.None, PictureDecoder.TryDecode(Encoded, out var picture));
        Assert.AreEqual((24, 16, true), (picture!.Width, picture.Height, picture.IsComplete));
        var bgra = picture.Bgra.ToArray();
        var apart = 0;
        for (var i = 0; i < Reference.Length; i++)
        {
            var mine = bgra[i / 3 * 4 + 2 - i % 3];
            var difference = Math.Abs(mine - Reference[i]);
            Assert.IsTrue(difference <= 3, $"channel {i}: {mine} for {Reference[i]}");
            apart += difference > 1 ? 1 : 0;
        }

        Assert.IsTrue(apart <= Reference.Length / 50, $"{apart} channels apart by more than 1");
    }
